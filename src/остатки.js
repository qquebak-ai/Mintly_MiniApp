/* Остатки кошелька приложения — одно число на всё приложение.
 *
 * Окна с «Макс» — запуск, сделка, вывод, обмен — спрашивали остаток
 * каждое само, полным опросом кошелька, а пока ответа не было,
 * подставляли что придётся: форма запуска показывала «Макс 31,5» —
 * потолок кривой — при пяти SOL на кошельке, окно сделки — «Доступно:
 * 0». Теперь число одно: его пишет любой опрос кошелька (appWallet.js),
 * окна берут его сразу и подписываются на свежее. Последнее известное
 * переживает и перезапуск — в localStorage, под id аккаунта: открыл
 * форму, и предел уже на месте, а сеть его только уточняет.
 *
 * Модуль крошечный и грузится вместе с приложением, а не по требованию,
 * как appWallet: число нужно в первом же кадре окна.
 */

import { supabase } from "./supabaseClient";

const КЛЮЧ = "mintly_ostatki_v1";
const числа = {};   // сеть -> { v, t }
let чей = null;      // id аккаунта, чьи это числа
const слушатели = new Set();

/* Своя трата, которую сеть ещё не показала: купил на 2 SOL — «Макс» в
   ту же секунду должен стать на 2 меньше, а узел видит сделку через
   секунду-другую, TON и EVM — ещё позже. Поправка держится, пока сеть
   не покажет списание сама (число упало хотя бы на половину суммы), и
   не дольше сорока пяти секунд: иначе отказ сети съел бы настоящие
   деньги, а встречная продажа не дала бы поправке сойти вовсе. */
const списания = {}; // сеть -> [{ сумма, было, до }]
const СПИСАНИЕ_МС = 45_000;

/* Чей вход сейчас — без похода в сеть: Supabase держит сессию в
   localStorage под ключом sb-<проект>-auth-token. */
function входСейчас() {
  try {
    for (let i = 0; i < localStorage.length; i += 1) {
      const к = localStorage.key(i);
      if (!к || !/^sb-.+-auth-token$/.test(к)) continue;
      const j = JSON.parse(localStorage.getItem(к) || "null");
      const id = j && j.user && j.user.id;
      if (id) return String(id);
    }
  } catch { /* приватный режим — памяти нет */ }
  return null;
}

(function поднять() {
  try {
    const j = JSON.parse(localStorage.getItem(КЛЮЧ) || "null");
    const кто = входСейчас();
    if (!j || !кто || j.чей !== кто || !j.числа) return;
    чей = кто;
    for (const [сеть, з] of Object.entries(j.числа)) {
      if (з && Number.isFinite(з.v)) числа[сеть] = { v: з.v, t: Number(з.t) || 0 };
    }
  } catch { /* испорчено — начнём с пустого */ }
})();

function сохранить() {
  try { localStorage.setItem(КЛЮЧ, JSON.stringify({ чей, числа })); } catch { /* нет места */ }
}

function оповестить() {
  for (const ф of слушатели) {
    try { ф(); } catch { /* один сломанный слушатель не мешает остальным */ }
  }
}

function живыеСписания(сеть) {
  const з = числа[сеть];
  const сейчас = Date.now();
  const ряд = (списания[сеть] || []).filter((с) => с.до > сейчас && !(з && з.v <= с.было - с.сумма / 2));
  списания[сеть] = ряд;
  return ряд;
}

/* Остаток монеты сети: sol, ton, bsc, base, eth. null — не знаем вовсе:
   ни разу не спрашивали или нет входа. Окно тогда показывает, что число
   грузится, а не подставляет чужой предел. */
export function остаток(сеть) {
  const з = числа[сеть];
  if (!з) return null;
  const v = живыеСписания(сеть).reduce((сумма, с) => сумма - с.сумма, з.v);
  return Math.max(0, v);
}

/* Число из сети без своих поправок — для проверок, у которых свой учёт
   сделок в пути (брони в корне приложения): вычесть трату дважды значило
   бы отказать в покупке, на которую деньги есть. */
export function сыройОстаток(сеть) {
  const з = числа[сеть];
  return з ? з.v : null;
}

// Сколько миллисекунд числу: по нему окно решает, переспрашивать ли сеть.
export function возрастОстатка(сеть) {
  const з = числа[сеть];
  return з ? Date.now() - з.t : Infinity;
}

/* Свежие числа из сети. кто — id аккаунта: числа другого аккаунта на
   этом же телефоне стираются, чужой остаток не покажется ни на миг. */
export function записатьОстатки(кто, свежие) {
  if (кто && чей && кто !== чей) {
    for (const к of Object.keys(числа)) delete числа[к];
    for (const к of Object.keys(списания)) delete списания[к];
  }
  if (кто) чей = кто;
  if (!чей) return;
  const сейчас = Date.now();
  let сдвиг = false;
  for (const [сеть, v] of Object.entries(свежие || {})) {
    if (v == null || !Number.isFinite(Number(v))) continue;
    const было = числа[сеть];
    if (!было || было.v !== Number(v)) сдвиг = true;
    числа[сеть] = { v: Number(v), t: сейчас };
  }
  сохранить();
  if (сдвиг) оповестить();
}

// Своя трата ушла в сеть — вычесть её, не дожидаясь узла.
export function списатьОстаток(сеть, сумма) {
  const s = Number(сумма);
  if (!числа[сеть] || !(s > 0)) return;
  const было = остаток(сеть);
  (списания[сеть] || (списания[сеть] = [])).push({ сумма: s, было, до: Date.now() + СПИСАНИЕ_МС });
  оповестить();
  // Поправка истекла сама — окна должны увидеть число без неё.
  setTimeout(оповестить, СПИСАНИЕ_МС + 50);
}

export function забытьОстатки() {
  for (const к of Object.keys(числа)) delete числа[к];
  for (const к of Object.keys(списания)) delete списания[к];
  чей = null;
  try { localStorage.removeItem(КЛЮЧ); } catch { /* приватный режим */ }
  оповестить();
}

export function следитьЗаОстатками(ф) {
  слушатели.add(ф);
  return () => { слушатели.delete(ф); };
}

/* Вышел из аккаунта или вошёл в другой — прежние числа больше не его. */
try {
  supabase.auth.onAuthStateChange((событие, сессия) => {
    const кто = сессия && сессия.user && сессия.user.id;
    if (событие === "SIGNED_OUT" || (кто && чей && кто !== чей)) забытьОстатки();
  });
} catch { /* без подписки числа всё равно сверяются по id при записи */ }
