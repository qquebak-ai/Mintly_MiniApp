-- помнит, что он это сделал: пока её нет, раздел «Кошелёк» показывает
-- экран создания, а после — обычный кошелёк.
--
-- Таблица app_seeds закрыта политиками целиком: читает и пишет её только
-- сервер своим service_role ключом, поэтому новых разрешений не нужно.

alter table public.app_seeds
  add column if not exists confirmed_at timestamptz;

