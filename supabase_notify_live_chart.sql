-- Живой график в чате — настройка человека, а не токена.
--
-- Раньше он включался на странице запуска и жил в самой записи токена
-- (tokens.live_chart). Но это не обещание покупателю, а поведение бота в
-- чате: решает его владелец чата, и решение одно на все свои токены.
--
-- Колонка выключена по умолчанию: бот не должен появляться в чате
-- сообщением, которого не просили. У токенов, запущенных раньше, флаг
-- остаётся в tokens.live_chart, и обход учитывает оба — миграция ничего
-- не ломает.

alter table public.profiles
  add column if not exists notify_live_chart boolean not null default false;
