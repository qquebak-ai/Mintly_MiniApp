-- Второй ключ ко входу: почта.
--
-- Аккаунт заводится Telegram-ом и держится на нём. Почта добавляется
-- потом и нужна для двух вещей: подтвердить вывод (деньги уходят
-- безвозвратно, и одной открытой сессии для них мало) и вернуть аккаунт,
-- если доступ к телеграму пропал.
--
-- Сам адрес хранит Supabase Auth — он же его и подтверждает письмом.
-- Здесь только отметка «человек включил подтверждение по почте»: без неё
-- вывод пришлось бы спрашивать код у всех подряд, в том числе у тех, у
-- кого адрес технический (tg<id>@telegram.local) и письма не доходят.

alter table public.profiles
  add column if not exists mail_2fa boolean not null default false;

comment on column public.profiles.mail_2fa is
  'Подтверждать вывод кодом с почты. Ставится после подтверждения адреса.';
