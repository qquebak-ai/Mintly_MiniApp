/* Частый опрос живых кривых: цена, собранное и свежие сделки.
 *
 *   GET /api/live?sol=<mint,…>&ton=<адрес кривой,…>
 *
 * Отвечает из памяти сервера (api/_live.js), поэтому его можно звать
 * каждые 0,3 секунды. Solana приходит потоком от узла — там задержка
 * равна времени блока. TON потока цен не даёт: состояние кривой сервер
 * перечитывает сам, не чаще TON_LIVE_MS на кривую (по умолчанию раз в
 * 0,4 с) — чаще не пустит лимит ключа tonapi.
 *
 * Переменные окружения: TONAPI_KEY, TON_LIVE_MS.
 */

import fs from "node:fs";
import path from "node:path";
import { прочитатьЖивое, записатьЖивое } from "./_live.js";
import { держатьКривую } from "./curve-stream.js";
import { ДЕМО_ТОКЕНЫ } from "./_demoTokens.js";

const ШАГ_TON_МС = Math.max(200, Number(process.env.TON_LIVE_MS) || 400);
const МАКС_КРИВЫХ_В_ЗАПРОСЕ = 60;
// Сколько запросов к tonapi разом: лимит ключа общий на весь сервер.
const МАКС_TON_РАЗОМ = 4;

/* Демо-токены — по одному в каждой сети. Сделок на них нет ни в одной
   цепочке: их разыгрывает сам сервер, той же формулой кривой x·y = k, что
   у настоящих. Темп — время блока своей сети в mainnet: сделка попадает в
   цепочку не чаще, чем выходит блок, и демо показывает ровно ту скорость,
   с какой лента, шапка и график будут жить на боевой сети.

   Время блока (mainnet):
     Solana    — слот 0,4 с;
     BNB Chain — 0,75 с (после обновлений 2025 года);
     Base      — 2 с;
     TON       — около 2,5 с на воркчейне;
     Ethereum  — 12 с.
   Резервы и суммы — в монете своей сети, в тех же пропорциях, что у
   настоящих кривых площадки. */
const ДЕМО_V_TOK = 1_073_000_000;
/* Темп и кривая — у сети общие, у каждого токена свои множители (см.
   api/_demoTokens.js): сколько сделок, какого размера и где на кривой он
   гуляет. Ключ ДЕМО_СЕТИ — ключ токена, не сети. */
// Те же пороги и запасы, что у настоящих кривых площадки: 1500 GRAM,
// 35 SOL, 4 BNB, 1,2 ETH; запас — порог × 30/85 (TON, Solana) или
// порог × 273/800 (EVM), как в контрактах.
const ОСНОВА_СЕТИ = {
  ton: { блокМс: 2500, вирт: 529.38, мин: 100, макс: 1400, цель: 1500, сделка: [0.3, 24], шанс: 0.17 },
  sol: { блокМс: 400, вирт: 12.35, мин: 1.2, макс: 33, цель: 35, сделка: [0.004, 0.2], шанс: 0.028 },
  bsc: { блокМс: 750, вирт: 1.365, мин: 0.14, макс: 3.8, цель: 4, сделка: [0.0007, 0.025], шанс: 0.052 },
  base: { блокМс: 2000, вирт: 0.4095, мин: 0.04, макс: 1.14, цель: 1.2, сделка: [0.00014, 0.0103], шанс: 0.14 },
  eth: { блокМс: 12000, вирт: 0.4095, мин: 0.04, макс: 1.14, цель: 1.2, сделка: [0.00022, 0.0105], шанс: 0.8 },
};
export const ДЕМО_СЕТИ = Object.fromEntries(ДЕМО_ТОКЕНЫ.map((т) => {
  const о = ОСНОВА_СЕТИ[т.сеть];
  // Узкая полоса вокруг своей точки пути: токены одной сети стоят на
  // разных капитализациях, а не все посередине.
  const центр = о.мин + (о.макс - о.мин) * т.путь;
  const ширина = (о.макс - о.мин) * 0.18;
  const мин = Math.max(о.мин, центр - ширина), макс = Math.min(о.макс, центр + ширина);
  return [т.ключ, {
    mint: т.mint, сеть: т.сеть, блокМс: о.блокМс, вирт: о.вирт, цель: о.цель,
    старт: центр, мин, макс,
    сделка: [о.сделка[0] * т.разм, о.сделка[1] * т.разм],
    шанс: Math.min(1, о.шанс * т.ск),
  }];
}));
// Размер сделки до того, как демо перестало торговать в каждом блоке, —
// для разового пересчёта уже набранного оборота.
const СТАРЫЕ_СДЕЛКИ = { ton: [0.5, 40], sol: [0.02, 1.5], bsc: [0.005, 0.3], base: [0.001, 0.08], eth: [0.002, 0.15] };
const ДЕНЬ_МС = 24 * 3600 * 1000;
/* История цены — для графика: свечи собираются из неё у телефона. Точка
   не чаще раза в секунду, двенадцать часов назад. */
const ДЕМО_ИСТОРИЯ_МС = 12 * 3600 * 1000;

const проданоПри = (с, собрано) => ДЕМО_V_TOK - (с.вирт * ДЕМО_V_TOK) / (с.вирт + собрано);
/* Состояние каждого демо: собранное, продано, время последнего блока,
   создан (от этого считается возраст), держатели, сутки сделок по
   минутам ([минута, сделок, монет]) и история цены ([мс, цена]). */
const демо = Object.fromEntries(Object.entries(ДЕМО_СЕТИ).map(([к, с]) => [к, {
  realSol: с.старт, sold: проданоПри(с, с.старт), прошлый: 0, создан: 0, держатели: 0, минуты: [], история: [],
  // Цена на начало каждой минуты за сутки — от неё считается «за 24 ч»:
  // история для графика хранится только двенадцать часов.
  цены24: [],
}]));

/* Состояние переживает перезапуск сервера: каждое обновление площадки
   перезапускает его, и графики начинались бы с нуля. Пишем в файл не
   чаще раза в десять секунд и читаем при старте. */
// Не во временную папку: у службы она своя (PrivateTmp) и стирается
// при каждом перезапуске. Каталог проекта службе писать разрешено.
const КАТАЛОГ_СОСТОЯНИЯ = process.env.LIVE_STATE_DIR || path.join(process.cwd(), ".state");
try { fs.mkdirSync(КАТАЛОГ_СОСТОЯНИЯ, { recursive: true }); } catch { /* нет прав — останется память */ }
// Новый файл при смене порогов: старая история цены посчитана по другой
// кривой, и график склеился бы обрывом.
const ФАЙЛ_ДЕМО = path.join(КАТАЛОГ_СОСТОЯНИЯ, "mintly-demo-v2.json");
function принять(к, з) {
  const д = демо[к];
  if (!д || !з || !Array.isArray(з.история) || !(з.realSol > 0)) return;
  д.история = з.история.filter((т) => Array.isArray(т) && т[1] > 0);
  д.realSol = з.realSol;
  д.sold = проданоПри(ДЕМО_СЕТИ[к], д.realSol);
  д.прошлый = Number(з.прошлый) || 0;
  д.создан = Number(з.создан) || (д.история[0] && д.история[0][0]) || 0;
  д.держатели = Number(з.держатели) || 0;
  if (Array.isArray(з.минуты)) д.минуты = з.минуты.filter((м) => Array.isArray(м) && м.length === 3);
  // Без этого пересчёт оборота повторялся бы после каждого перезапуска.
  д.оборотV2 = !!з.оборотV2;
  if (Array.isArray(з.цены24)) д.цены24 = з.цены24.filter((м) => Array.isArray(м) && м[1] > 0);
  // Прежний файл суточных цен не знал — берём их из истории графика.
  if (!д.цены24.length) for (const [мс, ц] of д.история) {
    const м = Math.floor(мс / 60000);
    if (!д.цены24.length || д.цены24[д.цены24.length - 1][0] !== м) д.цены24.push([м, ц]);
  }
}
try {
  const з = JSON.parse(fs.readFileSync(ФАЙЛ_ДЕМО, "utf8"));
  // Прежний файл хранил один демо-токен — тот, что в сети TON.
  if (з && з.сети) for (const к of Object.keys(з.сети)) принять(к, з.сети[к]);
  else принять("ton", з);
} catch { /* файла ещё нет — начинаем с чистой истории */ }
let демоСохранено = 0;
function сохранитьДемо() {
  if (Date.now() - демоСохранено < 10000) return;
  демоСохранено = Date.now();
  const данные = JSON.stringify({ сети: демо });
  fs.writeFile(ФАЙЛ_ДЕМО, данные, () => { /* не записалось — запишем в следующий раз */ });
}

/* В ответ — не каждая секунда: старше часа достаточно точки на
   пятнадцать секунд, иначе первый ответ весил бы полмегабайта. Для
   минутных свечей этого хватает, а последний час идёт полностью. */
function сжатьИсторию(д) {
  const граница = Date.now() - 3600 * 1000;
  const итог = [];
  let корзина = -1;
  for (const т of д.история) {
    if (т[0] >= граница) { итог.push(т); continue; }
    const к = Math.floor(т[0] / 15000);
    if (к === корзина) { итог[итог.length - 1] = [итог[итог.length - 1][0], т[1]]; continue; }
    корзина = к;
    итог.push(т);
  }
  return итог;
}

const ценаДемо = (к) => (ДЕМО_СЕТИ[к].вирт + демо[к].realSol) / (ДЕМО_V_TOK - демо[к].sold);
function записатьДемо(к) {
  записатьЖивое(ДЕМО_СЕТИ[к].mint, {
    price: ценаДемо(к),
    raised: демо[к].realSol, sold: демо[к].sold, graduation: ДЕМО_СЕТИ[к].цель, graduated: false,
  });
}
function запомнитьДемо(к, мс) {
  const д = демо[к];
  const минута = Math.floor(мс / 60000);
  const пм = д.цены24[д.цены24.length - 1];
  if (!пм || пм[0] !== минута) {
    д.цены24.push([минута, ценаДемо(к)]);
    const граница = Math.floor((Date.now() - ДЕНЬ_МС) / 60000);
    while (д.цены24.length && д.цены24[0][0] < граница) д.цены24.shift();
  }
  const последняя = д.история[д.история.length - 1];
  if (последняя && мс - последняя[0] < 1000) { последняя[1] = ценаДемо(к); return; }
  д.история.push([мс, ценаДемо(к)]);
}
function учестьСделкуДемо(к, мс, монет, покупка) {
  const д = демо[к];
  const минута = Math.floor(мс / 60000);
  const п = д.минуты[д.минуты.length - 1];
  if (п && п[0] === минута) { п[1] += 1; п[2] += монет; } else д.минуты.push([минута, 1, монет]);
  const граница = Math.floor((Date.now() - ДЕНЬ_МС) / 60000);
  while (д.минуты.length && д.минуты[0][0] < граница) д.минуты.shift();
  if (покупка ? Math.random() < 0.09 : Math.random() < 0.035) д.держатели = Math.max(1, д.держатели + (покупка ? 1 : -1));
}
function статистикаДемо(к) {
  const д = демо[к];
  const граница = Math.floor((Date.now() - ДЕНЬ_МС) / 60000);
  let сделок = 0, объём = 0;
  for (const [м, кол, о] of д.минуты) if (м >= граница) { сделок += кол; объём += о; }
  // X «создателя» демо-токена — официальный X площадки, если он задан
  // (MINTLY_X_HANDLE), по умолчанию — @Mintlycompany.
  const x = String(process.env.MINTLY_X_HANDLE || "Mintlycompany").replace(/^@/, "").trim();
  // Изменение за сутки — от цены сутки назад (или от самой ранней, если
  // демо моложе суток): один и тот же процент и в ленте, и в карточке.
  const тогда = д.цены24.length ? д.цены24[0][1] : 0;
  const change24 = тогда > 0 ? (ценаДемо(к) / тогда - 1) * 100 : 0;
  return { holders: д.держатели, tx24: сделок, vol24: объём, liquidity: д.realSol, change24, x: /^[A-Za-z0-9_]{1,15}$/.test(x) ? x : null };
}
function сделкаДемо(к, мс = Date.now()) {
  const с = ДЕМО_СЕТИ[к], д = демо[к];
  /* Сделка не в каждом блоке: иначе за сутки выходило сто тысяч сделок
     и оборот в сто с лишним раз больше капитализации — у живых токенов
     такого размера порядка шести тысяч сделок и оборот около десяти
     капитализаций. Шанс и размер сделки подобраны под эти цифры. */
  if (Math.random() >= (с.шанс ?? 1)) return;
  // Тянет к середине пути: собранное гуляет между мин и макс, а не уходит
  // в ноль или к выходу на биржу.
  const доля = (д.realSol - с.мин) / (с.макс - с.мин);
  const покупка = Math.random() < (доля < 0.15 ? 0.6 : доля > 0.85 ? 0.4 : 0.52);
  const [от, до] = с.сделка;
  const сумма = от + Math.random() ** 2 * (до - от);
  д.realSol = покупка ? д.realSol + сумма : Math.max(с.мин, д.realSol - сумма);
  учестьСделкуДемо(к, мс, сумма, покупка);
  д.sold = проданоПри(с, д.realSol);
}
/* Торговля идёт и тогда, когда никто не смотрит: пропущенное время
   доигрывается при следующем запросе — сделка на каждый блок, точка
   графика раз в секунду. Иначе после ночи без зрителей график стоял бы
   ровной линией на месте последнего визита. */
function шагДемо(к) {
  const с = ДЕМО_СЕТИ[к], д = демо[к];
  const сейчас = Date.now();
  // Новый токен не начинает с пустого графика: доигрываем ему те же
  // двенадцать часов, что хранит история, и «создаём» его чуть раньше.
  if (!д.прошлый) { д.прошлый = сейчас - ДЕМО_ИСТОРИЯ_МС; д.оборотV2 = true; записатьДемо(к); }
  if (!д.создан) д.создан = сейчас - ДЕМО_ИСТОРИЯ_МС - Math.round(Math.random() * 36 * 3600 * 1000);
  // Держателей до учёта не было — стартуем с обычного для такого
  // оборота числа, дальше его ведут сделки.
  if (!д.держатели) д.держатели = 140;
  // Учёт, набранный при сделке в каждом блоке, пересчитываем один раз под
  // новые шанс и размер — иначе раздутый оборот висел бы ещё сутки.
  if (!д.оборотV2) {
    const ср = ([от, до]) => от + (до - от) / 3;
    const было = СТАРЫЕ_СДЕЛКИ[к];
    const доля = с.шанс ?? 1;
    const размер = было ? ср(с.сделка) / ср(было) : 1;
    for (const м of д.минуты || []) { м[1] = Math.max(0, Math.round(м[1] * доля)); м[2] *= доля * размер; }
    д.оборотV2 = true;
  }
  // Дальше двенадцати часов не доигрываем: столько график и не хранит.
  if (сейчас - д.прошлый > ДЕМО_ИСТОРИЯ_МС) д.прошлый = сейчас - ДЕМО_ИСТОРИЯ_МС;
  let шагов = Math.floor((сейчас - д.прошлый) / с.блокМс);
  // Последние несколько сделок — живыми, с записью в ленту сделок;
  // остальное доигрывается молча, только в историю цены.
  const живых = Math.min(шагов, 10);
  while (шагов > живых) {
    д.прошлый += с.блокМс;
    сделкаДемо(к, д.прошлый);
    запомнитьДемо(к, д.прошлый);
    шагов -= 1;
  }
  if (живых && !прочитатьЖивое(с.mint)) записатьДемо(к);
  while (шагов-- > 0) {
    д.прошлый += с.блокМс;
    сделкаДемо(к, д.прошлый);
    записатьДемо(к);
    запомнитьДемо(к, д.прошлый);
  }
  while (д.история.length && сейчас - д.история[0][0] > ДЕМО_ИСТОРИЯ_МС) д.история.shift();
}

const адресSol = (s) => /^[1-9A-HJ-NP-Za-km-z]{32,44}$/.test(s);
const адресTon = (s) => /^-?\d:[0-9a-fA-F]{64}$/.test(s) || /^[A-Za-z0-9_-]{48}$/.test(s);

const опросTon = new Map(); // адрес -> { спрошено, идёт }
let tonВРаботе = 0;
/* Общий бюджет на tonapi: лимит у ключа один на весь сервер, и десять
   кривых по разу в 0,4 с упирались в 429 — отказ не приносил ничего.
   TON_LIVE_RPS запросов в секунду на всех (по умолчанию 4); кривые
   берутся по очереди, самая давняя — первой. */
const TON_RPS = Math.max(1, Number(process.env.TON_LIVE_RPS) || 4);
let tonПоследний = 0;

async function перечитатьTon(адрес) {
  let з = опросTon.get(адрес);
  if (!з) { з = { спрошено: 0, идёт: false }; опросTon.set(адрес, з); }
  if (з.идёт || Date.now() - з.спрошено < ШАГ_TON_МС || tonВРаботе >= МАКС_TON_РАЗОМ) return;
  if (Date.now() - tonПоследний < 1000 / TON_RPS) return;
  tonПоследний = Date.now();
  з.идёт = true;
  з.спрошено = Date.now();
  tonВРаботе += 1;
  try {
    const { состояние, цена, DEFAULT_VIRTUAL_TON, DEFAULT_VIRTUAL_TOKENS } = await import("./refresh-curves.js");
    const st = await состояние(адрес);
    if (!st) return;
    const params = { virtualTon: st.virtualTon || DEFAULT_VIRTUAL_TON, virtualTokens: st.virtualTokens || DEFAULT_VIRTUAL_TOKENS };
    записатьЖивое(адрес, {
      price: цена(st.realTon, params),
      raised: Number(st.realTon) / 1e9,
      sold: Number(st.tokensSold) / 1e9,
      graduation: Number(st.graduationTon) / 1e9,
      graduated: !!st.graduated,
    });
  } catch { /* сеть не ответила — отдадим прежнее */ } finally {
    з.идёт = false;
    tonВРаботе -= 1;
  }
}

function список(строка, проверка) {
  return [...new Set(String(строка || "").split(",").map((с) => с.trim()).filter(проверка))].slice(0, МАКС_КРИВЫХ_В_ЗАПРОСЕ);
}

export default async function handler(req, res) {
  res.setHeader("Cache-Control", "no-store");
  const sol = список(req.query && req.query.sol, адресSol);
  const ton = список(req.query && req.query.ton, адресTon);

  /* demo=1 — все демо, demo=sol,bsc — выбранные. */
  const демоЗапрос = String((req.query && req.query.demo) || "");
  const демоСети = демоЗапрос === "1" ? Object.keys(ДЕМО_СЕТИ) : демоЗапрос.split(",").filter((к) => ДЕМО_СЕТИ[к]);
  const сДемо = демоСети.length > 0;
  демоСети.forEach(шагДемо);
  if (сДемо) сохранитьДемо();
  // Опрос узла — только для одной открытой карточки; списку хватает потока.
  sol.forEach((mint) => держатьКривую(mint, { опрос: sol.length === 1 }));
  // Не ждём: отвечаем тем, что уже есть, а свежее заберёт следующий опрос.
  // Самая давно читанная — первой: так бюджет делится по кругу.
  [...ton].sort((a, b) => ((опросTon.get(a) || {}).спрошено || 0) - ((опросTon.get(b) || {}).спрошено || 0))
    .forEach((адрес) => { перечитатьTon(адрес); });

  const кривые = {};
  const сделки = {};
  for (const ключ of [...sol, ...ton, ...демоСети.map((к) => ДЕМО_СЕТИ[к].mint)]) {
    const з = прочитатьЖивое(ключ);
    if (!з || !з.событие) continue;
    const с = з.событие;
    кривые[ключ] = {
      price: с.price, raised: с.raised, sold: с.sold != null ? с.sold : null,
      graduation: с.graduation != null ? с.graduation : null,
      graduated: !!с.graduated, ms: с.ms,
      // Резервы Solana — график считает цену по ним, той же формулой,
      // что и весь ряд свечей; готовое число дало бы скачки свечи.
      ...(с.vSol != null ? { vSol: с.vSol, vTokens: с.vTokens, realSol: с.realSol } : null),
    };
    if (з.сделки.length) сделки[ключ] = з.сделки.slice(0, 30);
  }
  // history=<сеть> — история цены одного демо для графика; «1» — TON,
  // как раньше.
  const историяЧья = String((req.query && req.query.history) || "");
  const историяСеть = историяЧья === "1" ? "ton" : ДЕМО_СЕТИ[историяЧья] ? историяЧья : null;
  const история = историяСеть && демоСети.includes(историяСеть) ? сжатьИсторию(демо[историяСеть]) : undefined;
  const демоОтвет = сДемо ? {
    demos: Object.fromEntries(демоСети.map((к) => [к, { mint: ДЕМО_СЕТИ[к].mint, created: демо[к].создан, stats: статистикаДемо(к), blockMs: ДЕМО_СЕТИ[к].блокМс }])),
    // Прежние поля — для приложений, открытых до обновления.
    ...(демоСети.includes("ton") ? { demoCreated: демо.ton.создан, demoStats: статистикаДемо("ton") } : null),
  } : null;
  return res.status(200).json({ at: Date.now(), curves: кривые, trades: сделки, ...демоОтвет, ...(история ? { history: история } : null) });
}
