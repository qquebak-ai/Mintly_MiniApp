/* Частый опрос живых кривых: цена, собранное и свежие сделки.
 *
 *   GET /api/live?sol=<mint,…>&ton=<адрес кривой,…>
 *
 * Отвечает из памяти сервера (api/_live.js), поэтому его можно звать
 * каждые 0,3 секунды. Solana приходит потоком от узла — там задержка
 * равна времени блока. TON потока цен не даёт: состояние кривой сервер
 * перечитывает сам, не чаще TON_LIVE_MS на кривую (по умолчанию раз в
 * 0,4 с) — чаще не пустит лимит ключа tonapi.
 *
 * Переменные окружения: TONAPI_KEY, TON_LIVE_MS.
 */

import fs from "node:fs";
import path from "node:path";
import { прочитатьЖивое, записатьЖивое } from "./_live.js";
import { держатьКривую } from "./curve-stream.js";

const ШАГ_TON_МС = Math.max(200, Number(process.env.TON_LIVE_MS) || 400);
const МАКС_КРИВЫХ_В_ЗАПРОСЕ = 60;
// Сколько запросов к tonapi разом: лимит ключа общий на весь сервер.
const МАКС_TON_РАЗОМ = 4;

/* Демо-токен: сделок на нём нет ни в одной сети — их каждые 0,3 с
   разыгрывает сам сервер, той же формулой кривой, что у настоящих
   (x·y = k на виртуальных резервах Solana). Нужен, чтобы видеть, как
   быстро лента, шапка и график успевают за плотной торговлей. Живёт в
   ленте TON, поэтому и резервы как у кривой TON: 1000 монет виртуально. */
export const ДЕМО_MINT = "MintDemo1111111111111111111111111111111111";
const ДЕМО_ШАГ_МС = 300;
const ДЕМО_V_SOL = 1000;
const ДЕМО_V_TOK = 1_073_000_000;
// создан — когда демо-токен появился впервые: от этого считается его
// возраст. Раньше возраст брался с телефона («минуту назад» при каждом
// открытии), и через сутки везде стояло «10 мин».
const демо = { realSol: 400, sold: 0, прошлый: 0, создан: 0, держатели: 0 };
/* Сутки сделок демо-токена — по минутам: [минута, сделок, монет]. Из
   них карточка берёт объём и число сделок за сутки, а держателей сервер
   ведёт сам: покупка иногда приводит нового, продажа иногда уводит. */
let демоМинуты = [];
const ДЕНЬ_МС = 24 * 3600 * 1000;
демо.sold = ДЕМО_V_TOK - (ДЕМО_V_SOL * ДЕМО_V_TOK) / (ДЕМО_V_SOL + демо.realSol);
/* История цены демо-токена — для графика: свечи собираются из неё у
   телефона. Точка не чаще раза в секунду, двенадцать часов назад. */
const ДЕМО_ИСТОРИЯ_МС = 12 * 3600 * 1000;
let демоИстория = []; // [мс, цена]

/* История переживает перезапуск сервера: каждое обновление площадки
   перезапускает его, и график демо-токена начинался бы с нуля. Пишем её
   в файл не чаще раза в десять секунд и читаем при старте. */
// Не во временную папку: у службы она своя (PrivateTmp) и стирается
// при каждом перезапуске. Каталог проекта службе писать разрешено.
const КАТАЛОГ_СОСТОЯНИЯ = process.env.LIVE_STATE_DIR || path.join(process.cwd(), ".state");
try { fs.mkdirSync(КАТАЛОГ_СОСТОЯНИЯ, { recursive: true }); } catch { /* нет прав — останется память */ }
const ФАЙЛ_ДЕМО = path.join(КАТАЛОГ_СОСТОЯНИЯ, "mintly-demo.json");
try {
  const з = JSON.parse(fs.readFileSync(ФАЙЛ_ДЕМО, "utf8"));
  if (з && Array.isArray(з.история) && з.realSol > 0) {
    демоИстория = з.история.filter((т) => Array.isArray(т) && т[1] > 0);
    демо.realSol = з.realSol;
    демо.sold = ДЕМО_V_TOK - (ДЕМО_V_SOL * ДЕМО_V_TOK) / (ДЕМО_V_SOL + демо.realSol);
    демо.прошлый = Number(з.прошлый) || 0;
    демо.создан = Number(з.создан) || (демоИстория[0] && демоИстория[0][0]) || 0;
    демо.держатели = Number(з.держатели) || 0;
    if (Array.isArray(з.минуты)) демоМинуты = з.минуты.filter((м) => Array.isArray(м) && м.length === 3);
  }
} catch { /* файла ещё нет — начинаем с чистой истории */ }
let демоСохранено = 0;
function сохранитьДемо() {
  if (Date.now() - демоСохранено < 10000) return;
  демоСохранено = Date.now();
  const данные = JSON.stringify({ realSol: демо.realSol, прошлый: демо.прошлый, создан: демо.создан, держатели: демо.держатели, минуты: демоМинуты, история: демоИстория });
  fs.writeFile(ФАЙЛ_ДЕМО, данные, () => { /* не записалось — запишем в следующий раз */ });
}

/* В ответ — не каждая секунда: старше часа достаточно точки на
   пятнадцать секунд, иначе первый ответ весил бы полмегабайта. Для
   минутных свечей этого хватает, а последний час идёт полностью. */
function сжатьИсторию() {
  const граница = Date.now() - 3600 * 1000;
  const итог = [];
  let корзина = -1;
  for (const т of демоИстория) {
    if (т[0] >= граница) { итог.push(т); continue; }
    const к = Math.floor(т[0] / 15000);
    if (к === корзина) { итог[итог.length - 1] = [итог[итог.length - 1][0], т[1]]; continue; }
    корзина = к;
    итог.push(т);
  }
  return итог;
}

function ценаДемо() {
  return (ДЕМО_V_SOL + демо.realSol) / (ДЕМО_V_TOK - демо.sold);
}
function записатьДемо() {
  записатьЖивое(ДЕМО_MINT, {
    price: ценаДемо(),
    raised: демо.realSol, sold: демо.sold, graduation: 1500, graduated: false,
  });
}
function запомнитьДемо(мс) {
  const последняя = демоИстория[демоИстория.length - 1];
  if (последняя && мс - последняя[0] < 1000) { последняя[1] = ценаДемо(); return; }
  демоИстория.push([мс, ценаДемо()]);
}
function учестьСделкуДемо(мс, монет, покупка) {
  const минута = Math.floor(мс / 60000);
  const п = демоМинуты[демоМинуты.length - 1];
  if (п && п[0] === минута) { п[1] += 1; п[2] += монет; } else демоМинуты.push([минута, 1, монет]);
  const граница = Math.floor((Date.now() - ДЕНЬ_МС) / 60000);
  while (демоМинуты.length && демоМинуты[0][0] < граница) демоМинуты.shift();
  if (покупка ? Math.random() < 0.09 : Math.random() < 0.035) демо.держатели = Math.max(1, демо.держатели + (покупка ? 1 : -1));
}
function статистикаДемо() {
  const граница = Math.floor((Date.now() - ДЕНЬ_МС) / 60000);
  let сделок = 0, объём = 0;
  for (const [м, к, о] of демоМинуты) if (м >= граница) { сделок += к; объём += о; }
  return { holders: демо.держатели, tx24: сделок, vol24: объём, liquidity: демо.realSol };
}
function сделкаДемо(мс = Date.now()) {
  // Тянет к середине пути: собранное гуляет между 100 и 1400 монет, а
  // не уходит в ноль или к выходу на биржу.
  const покупка = Math.random() < (демо.realSol < 300 ? 0.6 : демо.realSol > 1200 ? 0.4 : 0.52);
  const сумма = 0.5 + Math.random() ** 2 * 40;
  демо.realSol = покупка ? демо.realSol + сумма : Math.max(100, демо.realSol - сумма);
  учестьСделкуДемо(мс, сумма, покупка);
  // Продано — по той же кривой: x·y = k, где k = V_SOL · V_TOK.
  демо.sold = ДЕМО_V_TOK - (ДЕМО_V_SOL * ДЕМО_V_TOK) / (ДЕМО_V_SOL + демо.realSol);
}
/* Торговля идёт и тогда, когда никто не смотрит: пропущенное время
   доигрывается при следующем запросе — сделка каждые 0,3 с, точка
   графика раз в секунду. Иначе после ночи без зрителей график стоял бы
   ровной линией на месте последнего визита. */
function шагДемо() {
  const сейчас = Date.now();
  if (!демо.прошлый) { демо.прошлый = сейчас - ДЕМО_ШАГ_МС; записатьДемо(); }
  if (!демо.создан) демо.создан = сейчас;
  // Держателей у демо-токена до учёта не было — стартуем с обычного для
  // такого оборота числа, дальше его ведут сделки.
  if (!демо.держатели) демо.держатели = 140;
  // Дальше двенадцати часов не доигрываем: столько график и не хранит.
  if (сейчас - демо.прошлый > ДЕМО_ИСТОРИЯ_МС) демо.прошлый = сейчас - ДЕМО_ИСТОРИЯ_МС;
  let шагов = Math.floor((сейчас - демо.прошлый) / ДЕМО_ШАГ_МС);
  // Последние несколько сделок — живыми, с записью в ленту сделок;
  // остальное доигрывается молча, только в историю цены.
  const живых = Math.min(шагов, 10);
  while (шагов > живых) {
    демо.прошлый += ДЕМО_ШАГ_МС;
    сделкаДемо(демо.прошлый);
    запомнитьДемо(демо.прошлый);
    шагов -= 1;
  }
  if (живых && !прочитатьЖивое(ДЕМО_MINT)) записатьДемо();
  while (шагов-- > 0) {
    демо.прошлый += ДЕМО_ШАГ_МС;
    сделкаДемо(демо.прошлый);
    записатьДемо();
    запомнитьДемо(демо.прошлый);
  }
  while (демоИстория.length && сейчас - демоИстория[0][0] > ДЕМО_ИСТОРИЯ_МС) демоИстория.shift();
  сохранитьДемо();
}

const адресSol = (s) => /^[1-9A-HJ-NP-Za-km-z]{32,44}$/.test(s);
const адресTon = (s) => /^-?\d:[0-9a-fA-F]{64}$/.test(s) || /^[A-Za-z0-9_-]{48}$/.test(s);

const опросTon = new Map(); // адрес -> { спрошено, идёт }
let tonВРаботе = 0;
/* Общий бюджет на tonapi: лимит у ключа один на весь сервер, и десять
   кривых по разу в 0,4 с упирались в 429 — отказ не приносил ничего.
   TON_LIVE_RPS запросов в секунду на всех (по умолчанию 4); кривые
   берутся по очереди, самая давняя — первой. */
const TON_RPS = Math.max(1, Number(process.env.TON_LIVE_RPS) || 4);
let tonПоследний = 0;

async function перечитатьTon(адрес) {
  let з = опросTon.get(адрес);
  if (!з) { з = { спрошено: 0, идёт: false }; опросTon.set(адрес, з); }
  if (з.идёт || Date.now() - з.спрошено < ШАГ_TON_МС || tonВРаботе >= МАКС_TON_РАЗОМ) return;
  if (Date.now() - tonПоследний < 1000 / TON_RPS) return;
  tonПоследний = Date.now();
  з.идёт = true;
  з.спрошено = Date.now();
  tonВРаботе += 1;
  try {
    const { состояние, цена, DEFAULT_VIRTUAL_TON, DEFAULT_VIRTUAL_TOKENS } = await import("./refresh-curves.js");
    const st = await состояние(адрес);
    if (!st) return;
    const params = { virtualTon: st.virtualTon || DEFAULT_VIRTUAL_TON, virtualTokens: st.virtualTokens || DEFAULT_VIRTUAL_TOKENS };
    записатьЖивое(адрес, {
      price: цена(st.realTon, params),
      raised: Number(st.realTon) / 1e9,
      sold: Number(st.tokensSold) / 1e9,
      graduation: Number(st.graduationTon) / 1e9,
      graduated: !!st.graduated,
    });
  } catch { /* сеть не ответила — отдадим прежнее */ } finally {
    з.идёт = false;
    tonВРаботе -= 1;
  }
}

function список(строка, проверка) {
  return [...new Set(String(строка || "").split(",").map((с) => с.trim()).filter(проверка))].slice(0, МАКС_КРИВЫХ_В_ЗАПРОСЕ);
}

export default async function handler(req, res) {
  res.setHeader("Cache-Control", "no-store");
  const sol = список(req.query && req.query.sol, адресSol);
  const ton = список(req.query && req.query.ton, адресTon);

  const сДемо = String((req.query && req.query.demo) || "") === "1";
  if (сДемо) шагДемо();
  // Опрос узла — только для одной открытой карточки; списку хватает потока.
  sol.forEach((mint) => держатьКривую(mint, { опрос: sol.length === 1 }));
  // Не ждём: отвечаем тем, что уже есть, а свежее заберёт следующий опрос.
  // Самая давно читанная — первой: так бюджет делится по кругу.
  [...ton].sort((a, b) => ((опросTon.get(a) || {}).спрошено || 0) - ((опросTon.get(b) || {}).спрошено || 0))
    .forEach((адрес) => { перечитатьTon(адрес); });

  const кривые = {};
  const сделки = {};
  for (const ключ of [...sol, ...ton, ...(сДемо ? [ДЕМО_MINT] : [])]) {
    const з = прочитатьЖивое(ключ);
    if (!з || !з.событие) continue;
    const с = з.событие;
    кривые[ключ] = {
      price: с.price, raised: с.raised, sold: с.sold != null ? с.sold : null,
      graduation: с.graduation != null ? с.graduation : null,
      graduated: !!с.graduated, ms: с.ms,
      // Резервы Solana — график считает цену по ним, той же формулой,
      // что и весь ряд свечей; готовое число дало бы скачки свечи.
      ...(с.vSol != null ? { vSol: с.vSol, vTokens: с.vTokens, realSol: с.realSol } : null),
    };
    if (з.сделки.length) сделки[ключ] = з.сделки.slice(0, 30);
  }
  const история = сДемо && String((req.query && req.query.history) || "") === "1" ? сжатьИсторию() : undefined;
  return res.status(200).json({ at: Date.now(), curves: кривые, trades: сделки, ...(сДемо ? { demoCreated: демо.создан, demoStats: статистикаДемо() } : null), ...(история ? { history: история } : null) });
}
