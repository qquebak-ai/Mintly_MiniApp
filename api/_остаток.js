/* Остаток кошелька для опроса интерфейса — быстро, даже когда узел думает.
 *
 * Окна с «Макс» (запуск, сделка, вывод, обмен) спрашивают остаток, чтобы
 * знать предел суммы. Публичные узлы тестовых сетей отвечают то за
 * десятую долю секунды, то за десять, и пока ответа не было, окно
 * подставляло что придётся: форма запуска показывала «Макс 31,5» —
 * потолок кривой — при пяти SOL на кошельке. Поэтому для опроса:
 *   - одно чтение на адрес за раз: окна и вкладки, спросившие разом,
 *     ждут один ответ узла, а не наваливаются на него пачкой;
 *   - ответ моложе полутора секунд отдаём из памяти сразу;
 *   - узел не уложился в ЖДЁМ_МС, а прежнее число есть — отдаём прежнее,
 *     чтение доигрывает в фоне и достаётся следующему опросу.
 * После своей сделки приложение просит свежее (свежее = true): прежнее
 * число тогда заведомо старое, и ответ ждёт сам узел.
 * Проверки перед тратой этим путём не ходят: там нужно число из сети, а
 * не из памяти.
 */

const записи = new Map(); // ключ -> { v, t, путь }
const СВЕЖО_МС = 1500;
const ЖДЁМ_МС = 1200;
/* Даже без прежнего числа дольше не держим: узел с повторами думает до
   двадцати секунд, а окно всё это время стоит без ответа. Вышел срок —
   null («не знаем»), чтение доигрывает в фоне для следующего опроса. */
const ПРЕДЕЛ_МС = 4000;
// Ключ — сеть и адрес; столько людей сразу сервер не держит и близко.
const МАКС_ЗАПИСЕЙ = 5000;

function запись(ключ) {
  let з = записи.get(ключ);
  if (!з) {
    if (записи.size >= МАКС_ЗАПИСЕЙ) записи.delete(записи.keys().next().value);
    з = { v: null, t: 0, путь: null };
    записи.set(ключ, з);
  }
  return з;
}

function прочестьВЗапись(з, прочитать) {
  return Promise.resolve()
    .then(прочитать)
    .then((v) => {
      if (v != null) { з.v = v; з.t = Date.now(); }
      return v;
    }, () => null);
}

async function неДольше(путь, мс) {
  let таймер = null;
  const срок = new Promise((r) => { таймер = setTimeout(() => r(null), мс); });
  const v = await Promise.race([путь, срок]);
  clearTimeout(таймер);
  return v;
}

export async function быстрыйОстаток(ключ, прочитать, { свежее = false } = {}) {
  const з = запись(ключ);
  if (свежее) {
    // Чтение, начатое до сделки, её не видит, — поэтому своё, отдельное.
    const v = await неДольше(прочестьВЗапись(з, прочитать), ПРЕДЕЛ_МС);
    return v != null ? v : з.v;
  }
  if (з.v != null && Date.now() - з.t < СВЕЖО_МС) return з.v;
  if (!з.путь) з.путь = прочестьВЗапись(з, прочитать).finally(() => { з.путь = null; });
  // Прежнего нет — ждём узел подольше: показать пока нечего.
  const v = await неДольше(з.путь, з.v == null ? ПРЕДЕЛ_МС : ЖДЁМ_МС);
  return v != null ? v : з.v;
}
