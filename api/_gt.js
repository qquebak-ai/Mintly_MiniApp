/* Один вход к бирже на весь сервер.
 *
 * У источника лимит на адрес — около тридцати запросов в минуту, и адрес
 * этот один на всех: и обход ленты, и свечи, и сделки каждой карточки
 * уходят с одного сервера. Пока каждый ходил сам по себе, лимит
 * выбирался за секунды, источник отвечал 429, приложение получало 502 и
 * шло к бирже напрямую с телефона — где упиралось в тот же отказ. Со
 * стороны это и есть «токены грузятся вечно или не грузятся вовсе».
 *
 * Поэтому все запросы идут через эту дверь:
 *
 *   • счётчик за минуту — больше лимита не выпускаем, лишние ждут;
 *   • одинаковые запросы, идущие разом, сливаются в один;
 *   • после отказа общая пауза: молотить в закрытую дверь бессмысленно,
 *     отказы считаются в тот же лимит.
 *
 * Ответ здесь не кешируется: у каждого вызывающего своя память и свои
 * сроки годности — свечам полминуты, описанию токена сутки.
 */

const ЛИМИТ_В_МИНУТУ = Number(process.env.GT_RATE_PER_MIN) || 24;
// Сколько ждать своей очереди, прежде чем сдаться. Дольше держать запрос
// нельзя: на том конце человек смотрит в пустой экран, и прошлый ответ
// из памяти вызывающего честнее долгого ожидания.
const ЖДАТЬ_МС = 3500;
// Пауза после отказа. Источник отвечает 429 не мгновенно отпуская: пока
// он сердится, любой следующий запрос — потраченный впустую.
const ПАУЗА_ПОСЛЕ_ОТКАЗА_МС = 15000;

const выпущено = [];      // времена последних запросов
const вПути = new Map();  // url -> Promise, чтобы не спрашивать дважды
let сердится = 0;         // до какого времени источник в отказе

const сон = (мс) => new Promise((r) => setTimeout(r, мс));

function очистить(сейчас) {
  while (выпущено.length && сейчас - выпущено[0] > 60000) выпущено.shift();
}

/* Дождаться своей очереди. Возвращает false, если ждать пришлось бы
   дольше отведённого — тогда вызывающий отдаёт что у него есть. */
async function очередь(ждатьМс) {
  const до = Date.now() + ждатьМс;
  for (;;) {
    const сейчас = Date.now();
    очистить(сейчас);
    if (сердится > сейчас) {
      if (сердится > до) return false;
      await сон(Math.min(400, сердится - сейчас));
      continue;
    }
    if (выпущено.length < ЛИМИТ_В_МИНУТУ) {
      выпущено.push(сейчас);
      return true;
    }
    const освободится = выпущено[0] + 60000;
    if (освободится > до) return false;
    await сон(Math.min(400, Math.max(50, освободится - сейчас)));
  }
}

/* Запрос к бирже. Возвращает { ok, status, json }: status 0 значит «даже
   не пошли» — очередь длиннее отведённого времени. */
export async function gtЗапрос(url, { ждать = ЖДАТЬ_МС } = {}) {
  const идёт = вПути.get(url);
  if (идёт) return идёт;

  const работа = (async () => {
    if (!(await очередь(ждать))) return { ok: false, status: 0, json: null };
    try {
      const res = await fetch(url, { headers: { accept: "application/json" } });
      if (res.status === 429 || res.status === 418) {
        сердится = Date.now() + ПАУЗА_ПОСЛЕ_ОТКАЗА_МС;
        return { ok: false, status: res.status, json: null };
      }
      if (!res.ok) return { ok: false, status: res.status, json: null };
      return { ok: true, status: res.status, json: await res.json() };
    } catch (err) {
      return { ok: false, status: -1, json: null, error: (err && err.message) || String(err) };
    } finally {
      вПути.delete(url);
    }
  })();

  вПути.set(url, работа);
  return работа;
}

/* Сколько запросов ещё можно сделать в этой минуте. Нужен обходу: он
   работает по кругу и может подождать следующего захода, а живой запрос
   с телефона ждать не может. */
export function gtЗапас() {
  очистить(Date.now());
  if (сердится > Date.now()) return 0;
  return Math.max(0, ЛИМИТ_В_МИНУТУ - выпущено.length);
}
