/* Одна операция с кошельком за раз.
 *
 * Запросы к кошельку приходят параллельно: два быстрых нажатия, две
 * вкладки, скрипт. Проверки «хватает ли», «не вышел ли предел за сутки»,
 * «какой номер у перевода» каждый запрос делал сам по себе — и все
 * проходили по одному и тому же состоянию. Так предел за сутки
 * обходился пачкой одновременных выводов, а два перевода TON получали
 * один номер, и сеть молча отбрасывала второй.
 *
 * Здесь — замок на кошелёк: пока идёт одна операция, вторая того же
 * кошелька получает отказ wallet_busy. Сервер — один процесс
 * (server/index.mjs), памяти процесса для этого хватает.
 */

const занятые = new Map(); // ключ -> { до }

// Срок замка — страховка от зависшего запроса: дольше двух минут ни
// одна операция не идёт, и кошелёк не должен запираться навсегда.
export function занять(ключ, срок = 120_000) {
  const сейчас = Date.now();
  const было = занятые.get(ключ);
  if (было && было.до > сейчас) throw Object.assign(new Error("wallet_busy"), { код: 409 });
  const метка = { до: сейчас + срок };
  занятые.set(ключ, метка);
  if (занятые.size > 5000) {
    for (const [к, м] of занятые) if (м.до <= сейчас) занятые.delete(к);
  }
  // Отпускает только свой замок: если срок вышел и кошелёк уже занял
  // другой запрос, его замок не трогаем.
  return () => { if (занятые.get(ключ) === метка) занятые.delete(ключ); };
}

/* Очередь вместо отказа — для кошельков площадки (казна): там ждут
   разные люди, и отказывать второму из-за первого незачем. */
const очереди = new Map(); // ключ -> хвост очереди

export function поочерёдно(ключ, дело) {
  const перед = очереди.get(ключ) || Promise.resolve();
  const итог = перед.then(дело);
  const хвост = итог.catch(() => {});
  очереди.set(ключ, хвост);
  хвост.then(() => { if (очереди.get(ключ) === хвост) очереди.delete(ключ); });
  return итог;
}

/* Номер перевода TON (seqno). Сеть принимает перевод не сразу, и пока
   номер не вырос, следующий перевод с тем же номером она отбросит —
   поэтому после отправки номер помним полторы минуты. */
const последнийНомер = new Map(); // ключ -> { seqno, at }

export async function свободныйНомер(открытый, ключ) {
  const seqno = await открытый.getSeqno();
  const было = последнийНомер.get(ключ);
  if (было && было.seqno >= seqno && Date.now() - было.at < 90_000) {
    throw Object.assign(new Error("wallet_busy"), { код: 409 });
  }
  return seqno;
}

export function занятьНомер(ключ, seqno) {
  последнийНомер.set(ключ, { seqno, at: Date.now() });
  if (последнийНомер.size > 5000) {
    const сейчас = Date.now();
    for (const [к, з] of последнийНомер) if (сейчас - з.at > 90_000) последнийНомер.delete(к);
  }
}

/* Дошёл ли до сети именно этот перевод TON. Рост seqno этого не
   доказывает: номер растёт от любого перевода, а фраза кошелька у
   человека на руках — он может отправить свой перевод с тем же номером
   из другого кошелька, и тогда наш отброшен, а номер всё равно вырос.
   Ищем транзакцию кошелька, чьё входящее сообщение — ровно наше
   подписанное тело, и смотрим, ушёл ли из неё перевод. */
export async function дождатьсяПеревода(client, адрес, тело, проверка, { ждать = 75_000 } = {}) {
  const хеш = тело.hash();
  const до = Date.now() + ждать;
  while (Date.now() < до) {
    await new Promise((r) => setTimeout(r, 1500));
    let список = [];
    try { список = await client.getTransactions(адрес, { limit: 8 }); } catch { continue; }
    for (const tx of список) {
      const вход = tx.inMessage;
      if (!вход || вход.info.type !== "external-in" || !вход.body.hash().equals(хеш)) continue;
      const исходящие = tx.outMessages.values();
      if (!исходящие.some(проверка)) throw new Error("ton_transfer_rejected");
      return tx.hash().toString("hex");
    }
  }
  throw new Error("ton_transfer_timeout");
}
