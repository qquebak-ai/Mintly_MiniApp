/* Внутренний вызов обработчика кошелька — от имени человека, но изнутри
 * сервера: так лимитная заявка, сработавшая по цене, проводит сделку тем
 * же путём, что и нажатие в приложении, со всеми его проверками.
 *
 * Метка — символ, а не заголовок или поле запроса: символ нельзя
 * прислать ни в JSON, ни в адресе, ни в заголовках, поэтому снаружи
 * выдать себя за внутренний вызов нечем. */
export const ВНУТРЕННИЙ_ВХОД = Symbol("mintly.внутренний-вход");

// Ответ-заглушка для вызова обработчика без сети: копит код и тело.
export function ответВнутри() {
  const о = {
    код: 200, тело: null, headersSent: false,
    setHeader() {}, end() { о.headersSent = true; },
    status(к) { о.код = к; return о; },
    json(т) { о.тело = т; о.headersSent = true; return о; },
  };
  return о;
}
