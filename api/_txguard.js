/* Разбор транзакции в общий вид: кто платит, какие инструкции и чем они
   заданы. Форматов два — старый и версионный, — но дальше нам нужно от
   них одно и то же. */
async function разобрать(base64) {
  const { Transaction, VersionedTransaction } = await import("@solana/web3.js");
  const байты = Uint8Array.from(Buffer.from(String(base64), "base64"));

  try {
    const v = VersionedTransaction.deserialize(байты);
    const ключи = v.message.staticAccountKeys.map((k) => k.toBase58());
    return {
      версионная: true,
      плательщик: ключи[0] || "",
      статических: ключи.length,
      инструкции: v.message.compiledInstructions.map((ins) => ({
        программа: ключи[ins.programIdIndex] || "",
        счета: Array.from(ins.accountKeyIndexes || []),
        данные: Buffer.from(ins.data || []),
      })),
      ключи,
    };
  } catch { /* не версионная — значит старого формата */ }

  const t = Transaction.from(байты);
  const ключи = [];
  const индекс = (k) => {
    const s = k.toBase58();
    if (!ключи.includes(s)) ключи.push(s);
    return ключи.indexOf(s);
  };
  const плательщик = t.feePayer ? t.feePayer.toBase58() : "";
  if (плательщик) ключи.push(плательщик);
  return {
    версионная: false,
    плательщик,
    статических: Infinity,
    инструкции: t.instructions.map((ins) => ({
      программа: ins.programId.toBase58(),
      счета: ins.keys.map((k) => индекс(k.pubkey)),
      данные: Buffer.from(ins.data),
    })),
    ключи,
  };
}

const номерСистемной = (данные) => (данные.length >= 4 ? данные.readUInt32LE(0) : -1);

/* Сколько монет уходит прямыми переводами. Считаем и «перевод», и
   «перевод с семенем», и создание счёта с деньгами: последнее — тоже
   уход средств, просто под другим именем. */
function переводы(инструкции) {
  let всего = 0;
  for (const ins of инструкции) {
    if (ins.программа !== СИСТЕМНАЯ) continue;
    const н = номерСистемной(ins.данные);
    if (н === СИС.ПЕРЕВОД && ins.данные.length >= 12) всего += Number(ins.данные.readBigUInt64LE(4));
    else if (н === СИС.СОЗДАТЬ && ins.данные.length >= 12) всего += Number(ins.данные.readBigUInt64LE(4));
    else if (н === СИС.ПЕРЕВОД_С_СЕМЕНЕМ && ins.данные.length >= 12) всего += Number(ins.данные.readBigUInt64LE(4));
  }
  return всего;
}

/* Главная проверка. Бросает исключение с понятной причиной — вызывающий
   код превращает её в отказ, а не в подпись.

   владелец      — адрес внутреннего кошелька;
   дело          — launch | trade | swap | withdraw;
   максПеревода  — потолок прямых переводов, в лямпортах;
   кривая        — адрес программы кривой площадки (её нет в общем
                   списке: он приходит из окружения и в разных сетях
                   разный). */
export async function проверитьТранзакцию(base64, { владелец, дело, максПеревода = 0, кривая = "" }) {
  const правила = ПРАВИЛА[дело];
  if (!правила) throw new Error(`неизвестное дело: ${дело}`);
  if (!владелец) throw new Error("не задан владелец");

  const t = await разобрать(base64);
  if (t.плательщик !== владелец) throw new Error("платит не наш кошелёк");
  if (!t.инструкции.length) throw new Error("пустая транзакция");

  const разрешённые = new Set(правила.программы);
  if (правила.кривая && кривая) разрешённые.add(кривая);

  for (const ins of t.инструкции) {
    if (!разрешённые.has(ins.программа)) {
      throw new Error(`запрещённая программа ${ins.программа.slice(0, 8)}…`);
    }
    if (ins.программа === СИСТЕМНАЯ) {
      const н = номерСистемной(ins.данные);
      if (!правила.системные.includes(н)) throw new Error(`запрещённая системная инструкция ${н}`);
    }
    if (ins.программа === ТОКЕНЫ || ins.программа === ТОКЕНЫ_2022) {
      const н = ins.данные.length ? ins.данные[0] : -1;
      if (!правила.токенные.includes(н)) throw new Error(`запрещённая инструкция токена ${н}`);
    }
  }

  // Потолок с запасом на аренду счетов: при покупке заводится счёт
  // токена, и его аренда уходит теми же переводами.
  const ушло = переводы(t.инструкции);
  if (ушло > максПеревода) {
    throw new Error(`перевод больше разрешённого: ${ушло} > ${максПеревода}`);
  }

  return { плательщик: t.плательщик, инструкций: t.инструкции.length, переведено: ушло };
}

