/* Живая цена кривой — потоком.
 *
 * Опрос раз в несколько секунд оставляет заметную паузу между чужой
 * сделкой и движением на графике. Здесь соединение держится открытым, а
 * сервер сам следит за кривыми и шлёт цену, как только она изменилась.
 *
 * Откуда приходит изменение. Все сделки площадки идут через одну её
 * программу, и счёт кривой меняется ровно в момент подтверждения сделки.
 * Поэтому сервер держит один вебсокет к узлу и подписан на счета этой
 * программы целиком (programSubscribe): узел сам присылает новое
 * содержимое счёта, как только оно записано в блок. Так же устроен и
 * pump.fun — у него тоже одна своя программа, и график рисуется из
 * собственного потока, а не из чужого агрегатора. Чужие токены сюда не
 * попадают по определению: у них другие программы и другие пулы.
 *
 * Опрос остался страховкой на случай, если вебсокет не поднялся или
 * оборвался: пока поток жив, он редкий, без потока — частый.
 *
 * Почему у сети спрашивает сервер, а не браузер: ключ к узлу живёт на
 * сервере и уходить в страницу не должен. Заодно подписка одна на всех —
 * сто открытых карточек стоят ровно столько же, сколько одна.
 *
 * Формат — Server-Sent Events: обычный HTTP, переживает прокси и сам
 * переподключается, в отличие от вебсокета.
 *
 *   GET /api/curve-stream?mint=<адрес>  — одна кривая, для карточки
 *   GET /api/curve-stream?all=1         — все сразу, для списков; в
 *                                         каждом событии есть mint
 *
 * Переменные окружения: SOLANA_RPC, SOLANA_CURVE_PROGRAM.
 */

import bs58 from "bs58";
import { поляКривой } from "./solana-launch.js";
import { записатьЖивое } from "./_live.js";

// Разрядность токена и лямпорты — те же, что в программе кривой.
const ЕДИНИЦА = 1e6;
const LAMPORTS = 1e9;

// Как часто спрашиваем состояние кривой, когда поток жив и когда нет.
// С потоком опрос — только страховка от пропущенного события.
const ШАГ_БЕЗ_ПОТОКА_МС = 900;
const ШАГ_С_ПОТОКОМ_МС = 5000;
// Пульс, чтобы прокси не счёл молчание обрывом.
const ПУЛЬС_МС = 20000;
// Никто не смотрит — перестаём спрашивать: цикл живёт ровно столько,
// сколько открыта хоть одна карточка.
const кривые = new Map(); // mint -> { зрители:Set, таймер, прошлое, пульс }
// Зрители общего потока: списки токенов, где важна любая кривая.
const общие = new Set();
// Последнее разосланное по каждой кривой — чтобы не повторять одно и то
// же, когда узел записал счёт, ничего в нём не изменив.
const последние = new Map(); // mint -> событие

const RPC = process.env.SOLANA_RPC || "";
const ПРОГРАММА = (process.env.SOLANA_CURVE_PROGRAM || "").trim();

const адресОк = (s) => typeof s === "string" && /^[1-9A-HJ-NP-Za-km-z]{32,44}$/.test(s);

async function состояниеКривой(mint) {
  try {
    const { состояние } = await import("./solana-launch.js");
    return await состояние(mint);
  } catch {
    return null;
  }
}

/* Одно событие потока. Отдаём не только цену, но и сами резервы: график
   считает цену своей формулой (через произведение резервов), и если
   прислать готовое число, посчитанное иначе, свеча начнёт прыгать между
   двумя значениями — одно от потока, другое от пересчёта. */
function событиеИзПолей(п) {
  const цена = (п.virtualSol + п.realSol) / (п.virtualTokens - п.tokensSold);
  return {
    price: (цена * ЕДИНИЦА) / LAMPORTS,
    raised: п.realSol / LAMPORTS,
    sold: п.tokensSold / ЕДИНИЦА,
    graduated: !!п.закрыта,
    vSol: п.virtualSol,
    vTokens: п.virtualTokens,
    realSol: п.realSol,
    at: Math.floor(Date.now() / 1000),
    // Время события в мс — по нему приложение не даёт старому событию
    // сдвинуть свечу назад после нового.
    ms: Date.now(),
  };
}

function событиеИзСостояния(st) {
  return {
    price: st.ценаSol,
    raised: st.solСобрано,
    sold: st.продано,
    graduated: !!st.закрыта,
    vSol: st.virtualSol,
    vTokens: st.virtualTokens,
    realSol: Math.round((st.solСобрано || 0) * LAMPORTS),
    at: Math.floor(Date.now() / 1000),
    // Время события в мс — по нему приложение не даёт старому событию
    // сдвинуть свечу назад после нового.
    ms: Date.now(),
  };
}

function написать(res, событие) {
  try { res.write(`data: ${JSON.stringify(событие)}\n\n`); } catch { /* зритель ушёл */ }
}

/* Разослать всем, кто ждёт эту кривую, и всем, кто слушает площадку
   целиком. Молчание тоже вредно: через прокси оно неотличимо от
   обрыва, поэтому раз в двадцать секунд повторяем последнее известное. */
/* Ожидаемой цены до блока здесь больше нет. Сервер рассылал итог своей
   сделки сразу после отправки, но сделка могла и не пройти (проскальзывание,
   предел частоты): ожидаемое оставалось в памяти и в ряду свечей как
   покупка, которой не было, и у свечи из одних покупок вырастала тень, а
   цена ещё долго стояла выше настоящей. Своя сделка и так видна в миг
   нажатия — её рисует сама карточка; остальным зрителям поток приносит
   её с обработанным блоком, через полсекунды. */
const слушатели = new Set();
const дляСлушателей = new Map(); // mint -> последнее, что получили слушатели

/* Слушать все кривые площадки: поток поднимается сразу и держится, даже
   когда ни одной карточки не открыто. Для бота уведомлений — ему нужны
   сделки всех токенов, а не только тех, на которые смотрят. */
export function слушатьКривые(f) {
  слушатели.add(f);
  поднятьПоток();
  return () => слушатели.delete(f);
}

function опубликовать(mint, событие, { силой = false, ожидание = false, опрос = false, порядок = null } = {}) {
  // Частый опрос (api/live.js) читает отсюда — пишем каждое состояние,
  // даже то, что потоку рассылать незачем. Память сверяет слот: более
  // раннее, чем уже известное, не рассылается никому — ни карточкам, ни
  // вестям (там оно стало бы ложной продажей).
  const итог = записатьЖивое(mint, событие, { ожидание, порядок });
  if (!итог.принято || !итог.событие) return;
  // Метка — когда состояние стало текущим: по ней телефон отличает
  // новое от повтора.
  событие = { ...событие, ms: итог.событие.ms };
  let запись = кривые.get(mint);
  // Последнее известное помним и для кривых, которые никто не открывал:
  // узел пишет счёт и тогда, когда собранное не изменилось, и без этой
  // памяти списки дёргались бы на пустом месте.
  const прошлое = (запись && запись.прошлое) || последние.get(mint) || null;
  const изменилось = !прошлое
    || Math.abs(прошлое.raised - событие.raised) > 1e-9
    || прошлое.graduated !== событие.graduated;
  /* Настоящее изменение (не своя ожидаемая сделка) — слушателям: по нему
     бот уведомлений пишет о сделке в тот же миг (api/notify.js). Сверяем
     со своим «последним»: ожидаемая сделка уже записала то же число в
     общее, и сравнение с ним проглотило бы настоящее подтверждение.
     опрос — состояние прочитано, а не пришло потоком: при живом потоке
     такое отстаёт от него, и вести верят ему с запасом. */
  if (!ожидание && слушатели.size) {
    const было = дляСлушателей.get(mint);
    if (!было || Math.abs(было.raised - событие.raised) > 1e-9 || было.graduated !== событие.graduated) {
      дляСлушателей.set(mint, { raised: событие.raised, graduated: событие.graduated });
      if (дляСлушателей.size > 5000) дляСлушателей.clear();
      for (const f of слушатели) { try { f(mint, событие, { опрос: опрос && живПоток }); } catch { /* слушатель не мешает потоку */ } }
    }
  }
  if (!изменилось && !силой) return;
  последние.set(mint, событие);
  if (последние.size > 500) {
    for (const ключ of последние.keys()) {
      if (последние.size <= 300) break;
      if (!кривые.has(ключ)) последние.delete(ключ);
    }
  }

  if (запись) {
    запись.прошлое = событие;
    запись.пульс = Date.now();
    for (const res of запись.зрители) написать(res, событие);
  }
  if (общие.size && изменилось) {
    const сМинтом = { mint, ...событие };
    for (const res of общие) написать(res, сМинтом);
  }
}

/* Поток изменений от узла.
 *
 * Одна подписка на всю программу: узел присылает счёт целиком, а в нём
 * лежит и mint (первый из четырёх адресов после трёх служебных байт), и
 * резервы. Разбирать транзакции не нужно — состояние кривой и есть итог
 * сделки. */
let сокет = null;
let живПоток = false;
let попытка = 0;

// Жив ли поток: по нему api/live.js говорит телефону, нужен ли ещё
// перечень кривых Solana в опросе.
export function потокЖив() { return живПоток; }
// Когда поток поднялся в последний раз: состояние, пришедшее раньше, могло
// пропустить сделки, пока поток лежал.
let потокПоднят = 0;

/* Состояние кривой из потока — для «Молнии»: сборка сделки берёт его,
   не спрашивая узел, и экономит круг к сети. Только пока поток жив и
   только то, что пришло после его подъёма: всё, что меняло кривую, поток
   принёс бы. */
export function состояниеИзПотока(mint) {
  if (!живПоток) return null;
  const с = последние.get(mint);
  if (!с || !(с.ms >= потокПоднят) || с.graduated) return null;
  if (!(с.vSol > 0) || !(с.vTokens > 0)) return null;
  return {
    virtualSol: с.vSol,
    virtualTokens: с.vTokens,
    realSol: с.realSol || 0,
    tokensSold: Math.round((с.sold || 0) * ЕДИНИЦА),
  };
}

function поднятьПоток() {
  if (сокет || typeof WebSocket !== "function") return;
  if (!RPC || !адресОк(ПРОГРАММА)) return;
  let s;
  try {
    s = new WebSocket(RPC.replace(/^http/i, "ws"));
  } catch {
    return;
  }
  сокет = s;

  s.onopen = () => {
    попытка = 0;
    живПоток = true;
    потокПоднят = Date.now();
    try {
      s.send(JSON.stringify({
        jsonrpc: "2.0", id: 1, method: "programSubscribe",
        // processed, а не confirmed: узел сообщает о записи счёта, как
        // только обработал блок, — на доли секунды раньше. Для графика
        // этого довольно: откатывается такой блок редко, а правильное
        // значение всё равно придёт следом.
        params: [ПРОГРАММА, { encoding: "base64", commitment: "processed" }],
      }));
    } catch { /* сокет закрылся на открытии — переподключимся ниже */ }
  };

  s.onmessage = (e) => {
    let j = null;
    try { j = JSON.parse(String(e.data)); } catch { return; }
    if (!j || j.method !== "programNotification") return;
    const значение = j.params && j.params.result && j.params.result.value;
    // Слот блока — порядок событий: обработанный блок иногда приходит
    // позже следующего, и без сверки его итог тянул бы свечу назад.
    const слот = Number(j.params && j.params.result && j.params.result.context && j.params.result.context.slot) || null;
    const данные = значение && значение.account && значение.account.data;
    const b64 = Array.isArray(данные) ? данные[0] : null;
    if (!b64) return;
    const буфер = Buffer.from(b64, "base64");
    const поля = поляКривой(буфер);
    if (!поля) return;
    const событие = событиеИзПолей(поля);
    // Счёт может оказаться чужим или недописанным: цена тогда выходит
    // не числом, и слать такое в списки нельзя — они покажут ноль.
    if (!Number.isFinite(событие.price) || !(событие.price > 0)) return;
    let mint = "";
    try { mint = bs58.encode(буфер.subarray(3, 35)); } catch { return; }
    if (!адресОк(mint)) return;
    опубликовать(mint, событие, { порядок: слот });
  };

  const упал = () => {
    живПоток = false;
    if (сокет === s) сокет = null;
    // Переподключение с нарастающей паузой: узел мог отбиться по лимиту,
    // и биться в него каждую секунду — верный способ там и остаться.
    попытка = Math.min(попытка + 1, 6);
    setTimeout(поднятьПоток, Math.min(30000, 1000 * 2 ** (попытка - 1)));
  };
  s.onclose = упал;
  s.onerror = () => { try { s.close(); } catch { упал(); } };
}

function следить(mint) {
  let запись = кривые.get(mint);
  if (запись) return запись;
  запись = { зрители: new Set(), прошлое: null, таймер: null, пульс: 0 };
  кривые.set(mint, запись);

  запись.таймер = setInterval(async () => {
    // Кривую держит и частый опрос: пока его спрашивают, следим дальше.
    if (!запись.зрители.size && Date.now() > (запись.нуженДо || 0)) {
      clearInterval(запись.таймер);
      кривые.delete(mint);
      return;
    }
    // С живым потоком опрос нужен реже: он лишь подстраховывает от
    // пропущенного события, а цену приносит подписка.
    if (живПоток && Date.now() - запись.пульс < ШАГ_С_ПОТОКОМ_МС) return;
    const начало = Date.now();
    const st = await состояниеКривой(mint);
    if (!st) return;
    // Пока шло чтение, поток принёс новее: чтение видит подтверждённое и
    // отстаёт от потока — его итог тянул бы свечу назад к цене до сделки.
    if (запись.пульс > начало) return;
    опубликовать(mint, событиеИзСостояния(st), { силой: Date.now() - запись.пульс > ПУЛЬС_МС, опрос: true, порядок: st.слот || null });
  }, ШАГ_БЕЗ_ПОТОКА_МС);

  return запись;
}

/* Для частого опроса: поднять поток и последить за кривой, пока её
   спрашивают. Зрителей-соединений у опроса нет, поэтому срок продлевается
   каждым запросом. */
export function держатьКривую(mint, { опрос = true } = {}) {
  if (!адресОк(mint)) return;
  поднятьПоток();
  // Для списков — только поток: свой опрос на каждую из десятков кривых
  // стоил бы запрос к узлу в секунду на каждую.
  if (!опрос) return;
  const запись = следить(mint);
  запись.нуженДо = Date.now() + 5000;
}

export default async function handler(req, res) {
  const все = String((req.query && req.query.all) || "") === "1";
  const mint = String((req.query && req.query.mint) || "").trim();
  if (!все && !адресОк(mint)) return res.status(400).json({ error: "bad_mint" });

  res.setHeader("Content-Type", "text/event-stream; charset=utf-8");
  res.setHeader("Cache-Control", "no-store, no-transform");
  res.setHeader("Connection", "keep-alive");
  // Nginx иначе копит поток в буфере и отдаёт его пачкой — вся затея
  // теряет смысл.
  res.setHeader("X-Accel-Buffering", "no");
  if (res.flushHeaders) res.flushHeaders();
  res.write(": ok\n\n");

  поднятьПоток();

  if (все) {
    общие.add(res);
    const закрыть = () => {
      общие.delete(res);
      try { res.end(); } catch { /* уже закрыт */ }
    };
    req.on("close", закрыть);
    req.on("error", закрыть);
    return;
  }

  const запись = следить(mint);
  запись.зрители.add(res);
  // Последнее известное — сразу, чтобы карточка не ждала первой сделки.
  if (запись.прошлое) написать(res, запись.прошлое);

  const закрыть = () => {
    запись.зрители.delete(res);
    try { res.end(); } catch { /* уже закрыт */ }
  };
  req.on("close", закрыть);
  req.on("error", закрыть);
}
