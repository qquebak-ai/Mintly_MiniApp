/* Скорость сделки: что она даёт и сколько стоит — одна таблица на сервер
 * и приложение (приложение читает её через /api/speed).
 *
 * Доплата из двух частей. Сети — чаевые за место в ближайшем блоке:
 * в Solana это надбавка за единицу вычислений и чаевые Jito (Jito есть
 * только в основной сети), в EVM — чаевые валидатору; в TON аукциона за
 * блок нет, и сетевой части там нет. Площадке — наценка за быстрый путь
 * на сервере: «Молния» держит сделку в отдельной дороге — рассылка в
 * несколько узлов разом, частые повторы и проверки, состояние кривой из
 * потока без лишнего похода в сеть. Наценка уходит тем же переводом,
 * что и сделка, на кошелёк комиссии площадки.
 *
 * Что меняется по скоростям (кроме платы):
 *   normal — сделка считается прошедшей, когда сеть её подтвердила
 *            (confirmed): надёжнее, но на полсекунды-секунду дольше;
 *   fast   — достаточно обработанного блока (processed), повтор раз в
 *            0,6 с, чаевые сети;
 *   turbo  — то же плюс дорога без ожиданий: повтор раз в 0,2 с во все
 *            узлы, проверка исхода каждые 0,15 с, состояние кривой из
 *            потока, журнал пишется параллельно со сборкой.
 */

export const СКОРОСТИ = ["normal", "fast", "turbo"];

export function скоростьИз(значение) {
  return СКОРОСТИ.includes(значение) ? значение : "fast";
}

/* Наценка площадке — в монете сети, за одну сделку. Порядок величин —
   около пяти центов за «Быстро» (Pro) и около двадцати пяти за «Молнию»
   (Turbo) по нынешним курсам: заметно меньше комиссий торговых ботов
   и при этом не копейки, ради которых не стоило заводить отдельный путь. */
export const НАЦЕНКА = {
  solana: { normal: 0, fast: 0.0004, turbo: 0.002 },
  ton: { normal: 0, fast: 0.02, turbo: 0.1 },
  bsc: { normal: 0, fast: 0.0001, turbo: 0.0004 },
  base: { normal: 0, fast: 0.00002, turbo: 0.00008 },
  eth: { normal: 0, fast: 0.00002, turbo: 0.00008 },
};

/* Ту же наценку можно платить монетами приложения — теми, что дают за
   приглашённых друзей и достижения (coins_balance в supabase_shop_server.sql).
   Цена в монетах одна на все сети: монета приложения не привязана к
   курсу сети. Сеть свою часть (чаевые за блок) берёт как прежде — её
   монетами не оплатить, она уходит валидаторам. */
export const НАЦЕНКА_МОНЕТАМИ = { normal: 0, fast: 3, turbo: 12 };

/* Сколько монет приложения спишется за эту сделку: 0 — платит монетой
   сети (не просил монетами, скорость обычная или монет не хватает).
   Списываются они после того, как сделка прошла (списатьМонетыЗаСкорость),
   а здесь только проверка остатка: неудавшаяся сделка монет не стоит. */
export async function монетыЗаСкорость(db, userId, скорость, хочет) {
  const цена = НАЦЕНКА_МОНЕТАМИ[скоростьИз(скорость)] || 0;
  if (!хочет || !цена || !db || !userId) return 0;
  try {
    const { data, error } = await db.rpc("coins_balance", { uid: userId });
    return !error && Number(data) >= цена ? цена : 0;
  } catch { return 0; }
}
export function списатьМонетыЗаСкорость(db, userId, монет) {
  if (!(монет > 0) || !db || !userId) return;
  Promise.resolve(db.rpc("speed_coins_charge", { p_user: userId, p_amount: монет }))
    .then((r) => { if (r && r.error) console.warn("[speed] монеты не списаны:", r.error.message); })
    .catch((e) => console.warn("[speed] монеты не списаны:", (e && e.message) || e));
}

export function наценка(сеть, скорость) {
  const т = НАЦЕНКА[сеть];
  return т ? Number(т[скоростьИз(скорость)]) || 0 : 0;
}

/* Как часто сервер повторяет и проверяет сделку — по скорости. */
export const ТЕМП = {
  normal: { повтор: 1000, проверка: 400, подтверждение: "confirmed" },
  fast: { повтор: 600, проверка: 300, подтверждение: "processed" },
  turbo: { повтор: 200, проверка: 150, подтверждение: "processed" },
};

export function темп(скорость) {
  return ТЕМП[скоростьИз(скорость)];
}
