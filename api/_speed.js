/* Скорость сделки: что она даёт и сколько стоит — одна таблица на сервер
 * и приложение (приложение читает её через /api/speed).
 *
 * Доплата из двух частей. Сети — чаевые за место в ближайшем блоке:
 * в Solana это надбавка за единицу вычислений и чаевые Jito (Jito есть
 * только в основной сети), в EVM — чаевые валидатору; в TON аукциона за
 * блок нет, и сетевой части там нет. Площадке — наценка за быстрый путь
 * на сервере: «Молния» держит сделку в отдельной дороге — рассылка в
 * несколько узлов разом, частые повторы и проверки, состояние кривой из
 * потока без лишнего похода в сеть. Наценка уходит тем же переводом,
 * что и сделка, на кошелёк комиссии площадки.
 *
 * Что меняется по скоростям (кроме платы):
 *   normal — сделка считается прошедшей, когда сеть её подтвердила
 *            (confirmed): надёжнее, но на полсекунды-секунду дольше;
 *   fast   — достаточно обработанного блока (processed), повтор раз в
 *            0,6 с, чаевые сети;
 *   turbo  — то же плюс дорога без ожиданий: повтор раз в 0,2 с во все
 *            узлы, проверка исхода каждые 0,15 с, состояние кривой из
 *            потока, журнал пишется параллельно со сборкой.
 */

export const СКОРОСТИ = ["normal", "fast", "turbo"];

export function скоростьИз(значение) {
  return СКОРОСТИ.includes(значение) ? значение : "fast";
}

// Наценка площадке — в монете сети, за одну сделку.
export const НАЦЕНКА = {
  solana: { normal: 0, fast: 0.0002, turbo: 0.001 },
  ton: { normal: 0, fast: 0.01, turbo: 0.05 },
  bsc: { normal: 0, fast: 0.00005, turbo: 0.0002 },
  base: { normal: 0, fast: 0.00001, turbo: 0.00005 },
  eth: { normal: 0, fast: 0.00001, turbo: 0.00005 },
};

export function наценка(сеть, скорость) {
  const т = НАЦЕНКА[сеть];
  return т ? Number(т[скоростьИз(скорость)]) || 0 : 0;
}

/* Как часто сервер повторяет и проверяет сделку — по скорости. */
export const ТЕМП = {
  normal: { повтор: 1000, проверка: 400, подтверждение: "confirmed" },
  fast: { повтор: 600, проверка: 300, подтверждение: "processed" },
  turbo: { повтор: 200, проверка: 150, подтверждение: "processed" },
};

export function темп(скорость) {
  return ТЕМП[скоростьИз(скорость)];
}
