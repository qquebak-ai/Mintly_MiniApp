/* Живое состояние кривых в памяти сервера — для частого опроса.
 *
 * Приложение спрашивает /api/live каждые 0,3 секунды. Сеть так часто
 * никто не спрашивает: сюда складывают своё всё, что сервер и так узнаёт
 * — поток Solana (curve-stream.js), толчки после своих сделок TON
 * (ton-stream.js) и опрос TON в api/live.js, — а ответ на опрос просто
 * читается отсюда. Сто телефонов стоят столько же, сколько один.
 *
 * Сделки выводятся из разницы двух состояний: выросло собранное —
 * покупка на разницу, упало — продажа. Подпись и кошелёк сюда не
 * попадают, их дочитывает обычная лента сделок, но сама сделка видна в
 * тот же миг, когда её увидел сервер.
 *
 * Старое назад не пускаем. Источников у одной кривой несколько, и они
 * отстают по-разному: поток Solana видит обработанный блок, опрос —
 * подтверждённый, а tonapi отвечает то с одного узла, то с другого.
 * Каждое запоздавшее чтение раньше ложилось поверх свежего: свеча
 * прыгала к цене до сделки и через секунду обратно, а в ленте сделок
 * появлялась продажа и тут же та же покупка. Теперь:
 *   - у кого есть порядок сети (слот Solana, блок и номер события EVM),
 *     тот не может перезаписать более позднее;
 *   - чтение без порядка (get-метод TON) вернуть кривую к состоянию,
 *     которое уже было и сменилось, может только подтверждённо: два
 *     чтения подряд, разнесённые хотя бы на полторы секунды. Узел,
 *     отставший на миг, так ничего не сдвинет, а настоящий возврат
 *     (купил и тут же продал всё) пройдёт с короткой задержкой.
 * Метка ms — когда состояние стало текущим, а не когда его в последний
 * раз прочитали: повторное чтение того же не выглядит для телефона
 * свежим событием и не перебивает свою сделку, нарисованную в миг
 * нажатия.
 */

const кривые = new Map(); // ключ (mint, адрес кривой или сеть:токен EVM) -> запись
const МАКС_СДЕЛОК = 40;
// Наблюдатели держат все кривые площадки разом — места с запасом.
const МАКС_КРИВЫХ = 4000;
// Счётчик к id сделки: за одну миллисекунду их бывает несколько.
let номер = 0;
// Сколько прежних состояний помним для сверки чтений и как долго.
const ПОМНИМ_СОСТОЯНИЙ = 8;
const ПОМНИМ_МС = 120_000;
// Возврат к прежнему состоянию по чтению — после такого подтверждения.
const ПОДТВЕРЖДЕНИЕ_МС = 1500;

// Отпечаток состояния: из собранного и проданного считается всё остальное.
const отпечатокИз = (с) => `${с.raised}|${с.sold}|${с.graduated ? 1 : 0}`;

/* Записать новое состояние.
 *
 * ожидание — своя сделка до блока: двигает цену сразу, но сделку не
 *   порождает (её породит настоящее состояние, иначе одна покупка
 *   выглядела бы как покупка и поправка к ней);
 * порядок — место события в сети, больше — позже;
 * чтение — состояние прочитано без порядка и могло отстать.
 *
 * Ответ: { принято, изменилось, событие } — событие с меткой ms, его и
 * рассылают дальше. Не принятое никуда не рассылается. */
export function записатьЖивое(ключ, событие, { ожидание = false, порядок = null, чтение = false } = {}) {
  if (!ключ || !событие || !(событие.price > 0)) return { принято: false, изменилось: false, событие: null };
  let з = кривые.get(ключ);
  if (!з) {
    if (кривые.size >= МАКС_КРИВЫХ) кривые.delete(кривые.keys().next().value);
    з = { событие: null, подтверждено: null, сделки: [], порядок: null, прежние: [], кандидат: null };
    кривые.set(ключ, з);
  }
  const сейчас = Date.now();
  if (порядок != null && з.порядок != null && порядок < з.порядок) {
    return { принято: false, изменилось: false, событие: з.событие };
  }
  const отпечаток = отпечатокИз(событие);
  const был = з.событие ? отпечатокИз(з.событие) : null;
  if (чтение && !ожидание && был != null) {
    if (отпечаток === был) {
      з.кандидат = null;
      return { принято: true, изменилось: false, событие: з.событие };
    }
    const прежнее = з.прежние.some((п) => п.отпечаток === отпечаток && сейчас - п.с < ПОМНИМ_МС);
    if (прежнее) {
      const к = з.кандидат;
      if (!к || к.отпечаток !== отпечаток) {
        з.кандидат = { отпечаток, с: сейчас, раз: 1 };
        return { принято: false, изменилось: false, событие: з.событие };
      }
      к.раз += 1;
      if (сейчас - к.с < ПОДТВЕРЖДЕНИЕ_МС) return { принято: false, изменилось: false, событие: з.событие };
    }
  }
  з.кандидат = null;
  if (порядок != null && !ожидание) з.порядок = порядок;

  const изменилось = был !== отпечаток || !з.событие || з.событие.price !== событие.price
    || з.событие.graduation !== событие.graduation;
  if (!изменилось) {
    // То же самое — свежее только поля без отпечатка (резервы, порог),
    // метка остаётся прежней.
    з.событие = { ...з.событие, ...событие, ms: з.событие.ms };
    if (!ожидание) з.подтверждено = з.событие;
    return { принято: true, изменилось: false, событие: з.событие };
  }
  /* Когда число в последний раз сдвинулось — по нему опрос «что
     изменилось после» (живыеПосле) отдаёт только сдвинувшиеся кривые:
     узел пишет счёт и без изменений, и без этой метки каждый ответ
     тащил бы всю память. */
  з.изменено = сейчас;
  if (был != null && был !== отпечаток) {
    з.прежние = з.прежние.filter((п) => п.отпечаток !== был && п.отпечаток !== отпечаток && сейчас - п.с < ПОМНИМ_МС);
    з.прежние.push({ отпечаток: был, с: сейчас });
    if (з.прежние.length > ПОМНИМ_СОСТОЯНИЙ) з.прежние.shift();
  }
  з.событие = { ...событие, ms: сейчас };
  if (ожидание) return { принято: true, изменилось: true, событие: з.событие };
  const п = з.подтверждено;
  з.подтверждено = з.событие;
  if (!п) return { принято: true, изменилось: true, событие: з.событие };
  const монет = (событие.raised || 0) - (п.raised || 0);
  if (Math.abs(монет) < 1e-9) return { принято: true, изменилось: true, событие: з.событие };
  const штук = событие.sold != null && п.sold != null
    ? Math.abs(событие.sold - п.sold)
    : Math.abs(монет) / событие.price;
  з.сделки.unshift({
    id: `${ключ.slice(-6)}:${сейчас}:${(номер = (номер + 1) % 1e6)}`,
    side: монет > 0 ? "buy" : "sell",
    coin: Math.abs(монет),
    tokens: штук,
    price: событие.price,
    // Состояние после сделки: по нему карточка ставит сделку на график
    // своей точкой, пока её нет в истории.
    raised: событие.raised,
    sold: событие.sold != null ? событие.sold : null,
    at: сейчас,
  });
  if (з.сделки.length > МАКС_СДЕЛОК) з.сделки.length = МАКС_СДЕЛОК;
  return { принято: true, изменилось: true, событие: з.событие };
}

export function прочитатьЖивое(ключ) {
  return кривые.get(ключ) || null;
}

/* Всё, что сдвинулось после метки, — для списков. Лента показывает сотни
   токенов, и перечислять их в каждом опросе незачем: сервер и так знает
   все кривые площадки (поток Solana, наблюдатели TON и EVM), а телефону
   нужны только перемены. Свежие — первыми. */
export function живыеПосле(мс, предел = 400) {
  const ряд = [];
  for (const [ключ, з] of кривые) {
    if (з.событие && (з.изменено || 0) > мс) ряд.push([ключ, з]);
  }
  ряд.sort((a, b) => b[1].изменено - a[1].изменено);
  return ряд.slice(0, предел);
}
